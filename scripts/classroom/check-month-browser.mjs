import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const output = resolve(root, 'docs/month-projects/2026-10-28');
const captures = resolve(output, 'screenshots');
mkdirSync(captures, { recursive: true });
const automation = await import(process.env.VPYLAB_PLAYWRIGHT_MODULE ? pathToFileURL(resolve(process.env.VPYLAB_PLAYWRIGHT_MODULE)).href : 'playwright');
const browser = await (automation.default || automation).chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--mute-audio'] });
const origin = 'http://127.0.0.1:4083';
const results = { testedAt: new Date().toISOString(), method: 'fresh-headless-Chromium + actual Pyodide/WebGL/WebAudio', audioScope: '실제 WebAudio 소스·음소거 상태 검증. 사람이 음질을 청취한 결과는 아님.', teams: {} };
async function prepare(id) {
  const context = await browser.newContext({ viewport: { width: 1580, height: 1200 }, deviceScaleFactor: 1.5, locale: 'ko-KR' });
  await context.route(/^https:\/\/(?:api\.)?github\.com\//, route => route.abort());
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(20000);
  await page.goto(`${origin}/month-projects.html#${id}`);
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent === '▶ 실행' && !button.disabled), null, { timeout: 120000 });
  await page.evaluate(async () => {
    window.__monthRegistry = await import('/src/engine/object-registry.js');
    window.__monthSound = await import('/src/engine/sound-system.js');
    window.__monthAudio = [];
    window.__monthSound.subscribeAudioState(state => window.__monthAudio.push({ ...state }));
  });
  await page.getByRole('button', { name: '▶ 실행', exact: true }).click();
  await page.locator('[data-vpylab-widgets]').waitFor();
  const record = results.teams[id] = { checks: [], errors, screenshots: [] };
  const pass = name => { record.checks.push(name); process.stdout.write(`통과: ${id} · ${name}\n`); };
  const clean = async () => {
    const console = await page.getByLabel('실행 출력').innerText();
    assert.doesNotMatch(console, /Traceback|NameError|\[event handler error\]/);
    assert.equal(await page.locator('.runtime-error').count(), 0);
    assert.deepEqual(errors, []);
    record.output = console;
  };
  const snapshot = () => page.evaluate(() => window.__monthRegistry.getSnapshot());
  const shot = async name => {
    await page.locator('.month-run-heading').evaluate(element => element.scrollIntoView({ block: 'start' }));
    await page.evaluate(() => window.scrollBy(0, -85));
    await page.screenshot({ path: resolve(captures, name), animations: 'disabled', caret: 'hide' });
    record.screenshots.push(name);
  };
  return { context, page, widgets: page.locator('[data-vpylab-widgets]'), record, pass, clean, snapshot, shot };
}
