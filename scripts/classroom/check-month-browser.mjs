try {
  const settled = await Promise.allSettled([course(), remix()]);
  for (let index = 0; index < settled.length; index++) if (settled[index].status === 'rejected') {
    results.teams[index === 0 ? 'course' : 'remix'].failure = settled[index].reason.message;
    process.stderr.write(`${index === 0 ? 'course' : 'remix'} 실패: ${settled[index].reason.message}\n`);
    process.exitCode = 1;
  }
  for (const context of browser.contexts()) for (const page of context.pages()) {
    const id = page.url().split('#')[1];
    if (!results.teams[id]?.failure) continue;
    results.teams[id].output = await page.getByLabel('실행 출력').innerText().catch(() => '화면을 읽지 못했습니다.');
    await page.screenshot({ path: resolve(captures, `${id}-failure.png`), fullPage: true }).catch(() => {});
  }
  results.completedAt = new Date().toISOString();
  writeFileSync(resolve(output, 'browser-validation.json'), JSON.stringify(results, null, 2) + '\n');
} finally { await browser.close(); }
